# Задача 1
# Даны числа x, у. Проверить истинность высказывания: «Точка с координатами (x, у) лежит во второй или третьей координатной четверти».
while True:
    try:
        x = float(input("Введите координату x: "))
        y = float(input("Введите координату y: "))

        # Точка не должна лежать на осях (x != 0 и y != 0)
        # Во II четверти: x < 0, y > 0. В III четверти: x < 0, y < 0.
        if x < 0 and y != 0:
            print("Истинно")
        else:
            print("Ложно")
        break
    except ValueError:
        print("Неправильно ввели! Нужно ввести число.")

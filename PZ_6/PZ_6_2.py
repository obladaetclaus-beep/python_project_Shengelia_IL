# Дан целочисленный список A размера N. Переписать в новый целочисленный
# список B все четные числа из исходного списка (в том же порядке)
# и вывести размер полученного списка B и его содержимое.

import random

# Ввод размера списка N
while True:
    try:
        n = int(input("Введите размер списка N (N > 0): "))
        if n <= 0:
            print("Размер должен быть положительным числом!")
            continue
        break
    except ValueError:
        print("Ошибка! Введите целое число.")

# Генерация исходного списка
a = []
for _ in range(n):
    a.append(random.randint(1, 50))

print(f"Исходный список A: {a}")

# Создаем список B только с четными числами
b = []
for item in a:
    if item % 2 == 0:
        b.append(item)

# Выводим результат
print(f"Результирующий список B (четные числа): {b}")
print(f"Размер полученного списка B: {len(b)}")

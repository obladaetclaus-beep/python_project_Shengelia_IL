# Дан целочисленный список A размера N. Переписать в новый целочисленный список B все четные числа из исходного списка (в том же порядке) и вывести размер полученного списка B и его содержимое.

import random

while True:
    try:
        n = int(input("Введите размер списка N (N > 0): "))
        if n > 0:
            break
        else:
            print("Размер должен быть положительным числом!")
    except ValueError:
        print("Ошибка! Введите целое число.")

a = [random.randint(1, 50) for _ in range(n)]
print(f"Исходный список A: {a}")

b = [x for x in a if x % 2 == 0]
print(f"Результирующий список B (четные числа): {b}")
print(f"Размер полученного списка B: {len(b)}")

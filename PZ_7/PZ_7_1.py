# Дан символ C и строка S. Удвоить каждое вхождение символа C в строку S.

# Ввод символа C
while True:
    c = input("Введите один символ C: ")
    if len(c) == 1:
        break
    print("Ошибка! Нужно ввести ровно один символ.")

# Ввод строки S
s = input("Введите исходную строку S: ")

# Формируем результирующую строку
res = ""
for char in s:
    if char == c:
        # Удваиваем символ
        res += char * 2
    else:
        res += char

# Вывод исходной и результирующей строк
print(f"Исходная строка:       '{s}'")
print(f"Результирующая строка: '{res}'")

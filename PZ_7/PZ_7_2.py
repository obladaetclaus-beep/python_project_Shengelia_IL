# Дана строка, состоящая из русских слов, разделенных пробелами
# (одним или несколькими). Найти количество слов в строке.

# Ввод строки с проверкой на непустой ввод
while True:
    text = input("Введите строку из слов: ")
    if text.strip() != "":
        break
    print("Ошибка! Введите строку, содержащую хотя бы одно слово.")

# Метод split() разделяет строку по пробелам любой длины
words = text.split()
word_count = len(words)

# Вывод результатов
print(f"Исходная строка: '{text}'")
print(f"Найденные слова: {words}")
print(f"Количество слов в строке: {word_count}")

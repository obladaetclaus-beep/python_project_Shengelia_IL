# Описать функцию AddRightDigit(D, K), добавляющую к целому положительному числу K
# справа цифру D (D — диапазон 0-9, K — параметр целого типа).
# С помощью этой функции последовательно добавить к числу K цифры D1 и D2,
# выводя результат каждого добавления.


def add_right_digit(d, k):
    """Добавляет цифру d справа к числу k."""
    return k * 10 + d


# Ввод исходного числа K
while True:
    try:
        k = int(input("Введите целое положительное число K: "))
        if k <= 0:
            print("Ошибка! Число K должно быть больше нуля.")
            continue
        break
    except ValueError:
        print("Ошибка! Нужно ввести целое число.")

# Ввод цифры D1
while True:
    try:
        d1 = int(input("Введите цифру D1 (от 0 до 9): "))
        if 0 <= d1 <= 9:
            break
        print("Ошибка! Цифра должна быть в диапазоне от 0 до 9.")
    except ValueError:
        print("Ошибка! Нужно ввести цифру.")

# Ввод цифры D2
while True:
    try:
        d2 = int(input("Введите цифру D2 (от 0 до 9): "))
        if 0 <= d2 <= 9:
            break
        print("Ошибка! Цифра должна быть в диапазоне от 0 до 9.")
    except ValueError:
        print("Ошибка! Нужно ввести цифру.")

# Добавление первой цифры
k = add_right_digit(d1, k)
print(f"После добавления цифры {d1} справа: {k}")

# Добавление второй цифры
k = add_right_digit(d2, k)
print(f"После добавления цифры {d2} справа: {k}")

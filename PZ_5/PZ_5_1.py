# и определяет, есть ли в числе одинаковые цифры.

import random


def check_same_digits():
    """Генерирует 4-значное число и проверяет, есть ли одинаковые цифры."""
    # Случайное четырехзначное число от 1000 до 9999
    num = random.randint(1000, 9999)
    print(f"Сгенерированное число: {num}")

    # Извлекаем отдельные цифры
    d1 = num // 1000
    d2 = (num // 100) % 10
    d3 = (num // 10) % 10
    d4 = num % 10

    # Проверяем все пары на совпадение
    if (d1 == d2 or d1 == d3 or d1 == d4 or
            d2 == d3 or d2 == d4 or d3 == d4):
        print("Результат: в числе есть одинаковые цифры.")
    else:
        print("Результат: все цифры в числе разные.")


# Запуск функции
check_same_digits()

# С начала суток прошло N секунд (N - целое).
# Найти количество секунд, прошедших с начала последнего часа.
while True:
    try:
        # Ввод числа пользователем
        N = int(input("Введите количество секунд: "))
        # Проверка числа на корректность (секунды должны быть больше или равны 0)
        if N >= 0:
            # Вычисляем остаток от деления на 1 час (3600 секунд)
            Six = N % 3600
            # Выводим результат
            print("Секунд с начала последнего часа: ", Six)
            break
        else:
            print("Ошибка: количество секунд не может быть отрицательным")
    # Выводится если это не число
    except ValueError:
        print("Ошибка: что-то пошло не так")

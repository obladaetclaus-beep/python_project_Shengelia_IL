# Дано целое число N (>0). Найти сумму 1 + 1/2 + 1/3 + ... + 1/N

# Ввод исходного числа N
while True:
    try:
        n = int(input("Введите целое положительное число N: "))
        if n <= 0:
            print("Ошибка! Число должно быть больше нуля.")
            continue
        break
    except ValueError:
        print("Ошибка! Введено не целое число.")

# Считаем сумму ряда с помощью цикла
total_sum = 0.0
i = 1

while i <= n:
    total_sum += 1 / i
    i += 1

# Вывод итогового результата
print(f"Сумма ряда 1 + 1/2 + ... + 1/{n} = {total_sum:.4f}")

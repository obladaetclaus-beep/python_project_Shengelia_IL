# Дано целое число N (> 1). Вывести наименьшее из целых чисел K, для которых
# сумма 1 + 2 + . . . + K будет больше или равна N, и саму эту сумму.

# Ввод исходного числа N
while True:
    try:
        n = int(input("Введите целое число N (> 1): "))
        if n <= 1:
            print("Ошибка! Число N должно быть строго больше 1.")
            continue
        break
    except ValueError:
        print("Ошибка! Введено не целое число.")

# Переменная K для перебора чисел и переменная для накапливания суммы
k = 1
current_sum = 0

# В цикле прибавляем K, пока сумма меньше N
while current_sum < n:
    current_sum += k
    if current_sum >= n:
        break
    k += 1

# Вывод найденного значения K и полученной суммы
print(f"Наименьшее число K: {k}")
print(f"Сумма чисел от 1 до {k}: {current_sum}")

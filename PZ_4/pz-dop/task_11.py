"""
Задание 11:
Дана арифметическая прогрессия a1=1, a2=4, a3=7, a4=10, a5=13, …
Составить программу, которая каждый элемент прогрессии разделит на 2
и результат округлит до ближайшего целого.
"""

while True:
    try:
        count = int(input("Введите количество элементов прогрессии: "))
        if count <= 0:
            print("Количество должно быть больше 0!")
            continue
        break
    except ValueError:
        print("Ошибка! Введите целое число.")

a = 1
d = 3

print("\nИсходный элемент -> Разделенный на 2 -> Округленный")
print("-" * 50)

for i in range(1, count + 1):
    half = a / 2
    # round() выполняет стандартное округление
    rounded = round(half)
    print(f"{a:16} -> {half:16.1f} -> {rounded:10}")
    a += d

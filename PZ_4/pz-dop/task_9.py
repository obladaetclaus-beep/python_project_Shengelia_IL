"""
Задание 9:
Посчитать и вывести количество элементов арифметической прогрессии
(a1 = 1, a2 = 4, a3 = 7, d = 3), удовлетворяющих условию 10 < ai < 30.
"""

# Начальный член и шаг прогрессии из примера занятия
a = 1
d = 3
count = 0

print("Элементы прогрессии в интервале (10, 30):")
# Перебираем члены прогрессии, пока они не превысят 30
while a < 30:
    if 10 < a < 30:
        print(a, end=" ")
        count += 1
    a += d

print(f"\nКоличество подходящих элементов: {count}")

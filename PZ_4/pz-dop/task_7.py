"""
Задание 7:
Даны два целых числа A и B (A < B). Вывести в порядке убывания все целые числа,
расположенные между A и B (включая сами числа A и B), а также количество этих
чисел (использовать оператор цикла).
"""

while True:
    try:
        a = int(input("Введите число A: "))
        b = int(input("Введите число B (B > A): "))
        if a >= b:
            print("Ошибка! Число A должно быть меньше B.")
            continue
        break
    except ValueError:
        print("Ошибка! Введите целые числа.")

print("Числа в порядке убывания:")
current = b
count = 0

# Цикл от B до A с шагом -1
while current >= a:
    print(current, end=" ")
    count += 1
    current -= 1

print(f"\nКоличество выведенных чисел: {count}")
